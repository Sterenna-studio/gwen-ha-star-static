-- Store public Gamer Profile results while keeping administrative reads private.
create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  client_result_id uuid not null unique,
  quiz_id text not null,
  quiz_version text not null,
  pseudonym text not null,
  global_level text not null,
  global_profile text not null,
  total_points smallint not null,
  max_points smallint not null,
  rond_percent smallint not null,
  carre_percent smallint not null,
  axis_scores jsonb not null,
  bonus_points smallint not null default 0,
  has_pets boolean not null default false,
  constraint quiz_results_quiz_id_check check (quiz_id = 'gamer-profile-test'),
  constraint quiz_results_version_check check (quiz_version ~ '^[0-9]+\.[0-9]+$' and length(quiz_version) <= 12),
  constraint quiz_results_pseudonym_check check (length(btrim(pseudonym)) between 1 and 60),
  constraint quiz_results_profile_check check (length(global_level) between 1 and 80 and length(global_profile) between 1 and 120),
  constraint quiz_results_points_check check (max_points between 1 and 200 and total_points between 0 and max_points and bonus_points between 0 and 20),
  constraint quiz_results_percent_check check (rond_percent between 0 and 100 and carre_percent between 0 and 100 and rond_percent + carre_percent = 100),
  constraint quiz_results_axes_check check (
    jsonb_typeof(axis_scores) = 'object'
    and axis_scores ?& array['organisation', 'anticipation', 'maintenance', 'hygiene_numerique', 'setup']
    and jsonb_typeof(axis_scores->'organisation') = 'number'
    and jsonb_typeof(axis_scores->'anticipation') = 'number'
    and jsonb_typeof(axis_scores->'maintenance') = 'number'
    and jsonb_typeof(axis_scores->'hygiene_numerique') = 'number'
    and jsonb_typeof(axis_scores->'setup') = 'number'
    and (axis_scores->>'organisation')::int between 0 and 100
    and (axis_scores->>'anticipation')::int between 0 and 100
    and (axis_scores->>'maintenance')::int between 0 and 100
    and (axis_scores->>'hygiene_numerique')::int between 0 and 100
    and (axis_scores->>'setup')::int between 0 and 100
  )
);

comment on table public.quiz_results is 'Résultats pseudonymisés du test Gamer Profile. Les données démographiques détaillées ne sont pas stockées.';
create index if not exists quiz_results_created_at_idx on public.quiz_results (created_at desc);
create index if not exists quiz_results_version_idx on public.quiz_results (quiz_id, quiz_version);

alter table public.quiz_results enable row level security;

drop policy if exists "quiz results: public insert" on public.quiz_results;
create policy "quiz results: public insert"
on public.quiz_results
for insert
to anon, authenticated
with check (
  quiz_id = 'gamer-profile-test'
  and length(btrim(pseudonym)) between 1 and 60
  and total_points between 0 and max_points
  and rond_percent + carre_percent = 100
);

drop policy if exists "quiz results: superuser read" on public.quiz_results;
create policy "quiz results: superuser read"
on public.quiz_results
for select
to authenticated
using ((select public._is_superuser()));

revoke all on table public.quiz_results from public, anon, authenticated;
grant insert on table public.quiz_results to anon, authenticated;
grant select on table public.quiz_results to authenticated;
revoke all on sequence public.quiz_results_id_seq from public, anon, authenticated;
grant usage on sequence public.quiz_results_id_seq to anon, authenticated;
